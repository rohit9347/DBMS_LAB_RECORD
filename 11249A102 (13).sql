-- Step 1: Create the EMPLOYEE Table
CREATE TABLE EMPLOYEE
(
    EMP_ID NUMBER(5) PRIMARY KEY,
    EMP_NAME VARCHAR2(30),
    SALARY NUMBER(8)
);

-- Step 2: Create EMP_AUDIT Table and Sequence
CREATE TABLE EMP_AUDIT
(
    AUDIT_ID NUMBER(5),
    EMP_ID NUMBER(5),
    ACTION_PERFORMED VARCHAR2(20),
    ACTION_DATE DATE
);

CREATE SEQUENCE EMP_AUDIT_SEQ START WITH 1 INCREMENT BY 1;

-- Step 3: Insert Initial Sample Records
INSERT INTO EMPLOYEE VALUES (101, 'ARUN', 35000);
INSERT INTO EMPLOYEE VALUES (102, 'BALA', 40000);
COMMIT;

-- Step 4: INSERT Trigger
CREATE OR REPLACE TRIGGER TRG_EMP_INSERT
AFTER INSERT ON EMPLOYEE
FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT
    VALUES (EMP_AUDIT_SEQ.NEXTVAL, :NEW.EMP_ID, 'INSERT', SYSDATE);
END;
/

-- Step 5: UPDATE Trigger
CREATE OR REPLACE TRIGGER TRG_EMP_UPDATE
AFTER UPDATE ON EMPLOYEE
FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT
    VALUES (EMP_AUDIT_SEQ.NEXTVAL, :NEW.EMP_ID, 'UPDATE', SYSDATE);
END;
/

-- Step 6: DELETE Trigger
CREATE OR REPLACE TRIGGER TRG_EMP_DELETE
AFTER DELETE ON EMPLOYEE
FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT
    VALUES (EMP_AUDIT_SEQ.NEXTVAL, :OLD.EMP_ID, 'DELETE', SYSDATE);
END;
/

-- Test INSERT Trigger
INSERT INTO EMPLOYEE VALUES (103, 'DIVYA', 45000);
COMMIT;

-- Test UPDATE Trigger
UPDATE EMPLOYEE SET SALARY = 50000 WHERE EMP_ID = 101;
COMMIT;

-- Test DELETE Trigger
DELETE FROM EMPLOYEE WHERE EMP_ID = 102;
COMMIT;

-- Verify Audit Trail
SELECT * FROM EMP_AUDIT;
SELECT * FROM EMPLOYEE;
