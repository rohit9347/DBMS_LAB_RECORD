-- Step 1: Create DEPARTMENT Table
CREATE TABLE DEPARTMENT
(
    DEPT_ID NUMBER(3) PRIMARY KEY,
    DEPT_NAME VARCHAR2(30)
);

-- Step 2: Insert into DEPARTMENT
INSERT INTO DEPARTMENT VALUES (101, 'CSE');
