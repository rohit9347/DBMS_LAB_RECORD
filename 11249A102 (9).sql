COMMIT;

SELECT E.EMP_NAME EMPLOYEE, M.EMP_NAME MANAGER
FROM EMPLOYEE E
LEFT JOIN EMPLOYEE M ON E.MANAGER_ID = M.EMP_ID;

-- 6. Subquery: Students Scoring Above Average Marks
SELECT STUDENT_NAME, MARKS
FROM STUDENT
WHERE MARKS > (SELECT AVG(MARKS) FROM STUDENT);

-- 7. Subquery with IN: Students in CSE Department
SELECT STUDENT_NAME
FROM STUDENT
WHERE DEPT_ID IN (SELECT DEPT_ID FROM DEPARTMENT WHERE DEPT_NAME = 'CSE');

-- 8. Correlated Subquery: Students with Maximum Marks in Their Department
SELECT STUDENT_NAME, MARKS, DEPT_ID
FROM STUDENT S1
WHERE MARKS = (
    SELECT MAX(MARKS)
    FROM STUDENT S2
    WHERE S1.DEPT_ID = S2.DEPT_ID
);
