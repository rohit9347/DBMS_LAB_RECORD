COMMIT;

-- 1. INNER JOIN
SELECT S.STUDENT_ID, S.STUDENT_NAME, D.DEPT_NAME
FROM STUDENT S
INNER JOIN DEPARTMENT D ON S.DEPT_ID = D.DEPT_ID;

-- 2. LEFT OUTER JOIN
SELECT S.STUDENT_NAME, D.DEPT_NAME
FROM STUDENT S
LEFT OUTER JOIN DEPARTMENT D ON S.DEPT_ID = D.DEPT_ID;

-- 3. RIGHT OUTER JOIN
SELECT S.STUDENT_NAME, D.DEPT_NAME
FROM STUDENT S
RIGHT OUTER JOIN DEPARTMENT D ON S.DEPT_ID = D.DEPT_ID;

-- 4. FULL OUTER JOIN
SELECT S.STUDENT_NAME, D.DEPT_NAME
FROM STUDENT S
FULL OUTER JOIN DEPARTMENT D ON S.DEPT_ID = D.DEPT_ID;

-- 5. SELF JOIN
CREATE TABLE EMPLOYEE
(
    EMP_ID NUMBER(5) PRIMARY KEY,
    EMP_NAME VARCHAR2(30),
    MANAGER_ID NUMBER(5)
);

INSERT INTO EMPLOYEE VALUES (1, 'RAJ', NULL);
