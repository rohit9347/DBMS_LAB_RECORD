-- 1NF: Remove repeating groups
CREATE TABLE STUDENT_COURSE_1NF
(
    STUDENT_ID NUMBER(5),
    STUDENT_NAME VARCHAR2(30),
    COURSE VARCHAR2(20)
);

-- 2NF: Remove partial dependencies
CREATE TABLE STUDENT_2NF
(
    STUDENT_ID NUMBER(5) PRIMARY KEY,
    STUDENT_NAME VARCHAR2(30)
);

CREATE TABLE STUDENT_COURSE_2NF
(
    STUDENT_ID NUMBER(5),
    COURSE VARCHAR2(20),
    PRIMARY KEY (STUDENT_ID, COURSE),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT_2NF(STUDENT_ID)
);

-- 3NF: Remove transitive dependencies
CREATE TABLE DEPARTMENT_3NF
(
    DEPT_ID VARCHAR2(5) PRIMARY KEY,
    DEPT_NAME VARCHAR2(30)
);

CREATE TABLE STUDENT_3NF
(
    STUDENT_ID NUMBER(5) PRIMARY KEY,
    STUDENT_NAME VARCHAR2(30),
    DEPT_ID VARCHAR2(5),
    FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT_3NF(DEPT_ID)
);

-- 4NF: Remove multivalued dependencies
CREATE TABLE STUDENT_HOBBY
(
    STUDENT_NAME VARCHAR2(30),
    HOBBY VARCHAR2(30)
);

CREATE TABLE STUDENT_LANGUAGE
(
    STUDENT_NAME VARCHAR2(30),
    LANGUAGE VARCHAR2(30)
);

-- 5NF: Remove join dependencies
CREATE TABLE SUPPLIER_PART
(
    SUPPLIER_ID VARCHAR2(5),
    PART_ID VARCHAR2(5)
);

CREATE TABLE PART_PROJECT
(
    PART_ID VARCHAR2(5),
    PROJECT_ID VARCHAR2(5)
);

CREATE TABLE SUPPLIER_PROJECT
(
    SUPPLIER_ID VARCHAR2(5),
    PROJECT_ID VARCHAR2(5)
);
